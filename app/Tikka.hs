-- Represents each flag which could be passed into the interpreter
data Flags = Flags
  { tracing :: Int
  , verbosity :: Int
  , dump :: String
  , stc :: Bool
  , visual :: Bool
  , repl :: Bool
  }
  deriving (Show)

-- Parses the given file (and it's imports) with the given flags, and either returns a parse error or (Text to dump, Text to output, Type + other errors)
parseAndEvaluateProject :: Flags -> String -> String -> IO (Either String (String, [String], String))
parseAndEvaluateProject flags file func = case parse getImports "" (pack file) of
  Left bundle -> pure (Left $ removeFirstFour $ errorBundlePretty bundle)
  Right (rest, fileNames) -> do
    files <- E.try (readFiles fileNames) :: IO (Either E.IOException [String])
    case files of
      Left err -> if isDoesNotExistError err then (pure . Left) $ "Error: The file/path '" ++ removeLastFour (head $ words $ show err) ++ "' does not exist, so could not be imported" else (pure . Left) $ "Error: " ++ show err
      Right fullFiles -> do
        let concatFile = rest ++ "\n" ++ Data.List.intercalate "\n" fullFiles
        case parseAndEvaluate flags concatFile func of
          Left s -> pure (Left $ removeFirstFour s)
          Right eval -> pure $ Right eval

-- removes the superfluous stack trace in error messages generated by MegaParsec
removeFirstFour :: String -> String
removeFirstFour s = if length (Prelude.lines s) > 4 then Prelude.unlines $ tail $ tail $ tail $ tail $ Prelude.lines s else s

removeLastFour :: [a] -> [a]
removeLastFour xs = take (length xs - 4) xs

-- Parses all import statements in the file
getImports :: Parser (String, [String])
getImports = do
  files <- many getImport
  file <- takeRest
  pure (unpack file, files ++ ["imports/command-line", "imports/local-decl", "imports/prelude"])

-- Parses an import statement
getImport :: Parser String
getImport = do
  lexeme "import"
  lexeme $ many $ noneOf [' ', '\n', '\r']

-- Reads all imported files
readFiles :: [String] -> IO [String]
readFiles [] = pure []
readFiles (x : xs) = do
  original <- E.try (readFile x) :: IO (Either E.IOException String)
  case original of
    Left _ -> do
      first <- readFile $ x ++ ".hs"
      rest <- readFiles xs
      pure (first : rest)
    Right first -> do
      rest <- readFiles xs
      pure (first : rest)

addToLocalDecl :: String -> IO ()
addToLocalDecl s = do
  file <- S.readFile "imports/local-decl"
  let toWrite = addDecl s (Prelude.lines file)
  writeFile "imports/local-decl" (Prelude.unlines toWrite)

addDecl :: String -> [String] -> [String]
addDecl s [] = [s ++ "\n"]
addDecl s (l : ls) = if strip (pack $ head $ splitOn "=" s) == strip (pack $ head $ splitOn "=" l) then s : tryTail ls else l : addDecl s ls
 where
  tryTail [] = []
  tryTail ls' = tail ls'

-- Parses the given file with the given flags, and either returns a parse error or (Text to dump, Text to output, Type + other errors)
parseAndEvaluate :: Flags -> String -> String -> Either String (String, [String], String)
parseAndEvaluate flags file func = case parseFile file func (stc flags) of
  Left s -> if clamp (1, 4) (verbosity flags) > 2 then Left s else Left $ printParseError (lines s)
  Right (evalSteps, errors, deSugared) -> do
    let t = clamp (1, 4) (tracing flags)
    let v = clamp (1, 4) (verbosity flags)
    let toPrint = if isTrace then outputTrace evalSteps t v func else output evalSteps t v func
    if stc flags
      then
        ( do
            let toDump = Data.List.intercalate "\n\n" (map dumpFileSTC (reverse deSugared)) ++ "\n"
            Right (toDump, toPrint, typeCheck v (last evalSteps) ++ printErrors v errors)
        )
      else
        ( do
            let toDump = Data.List.intercalate "\n\n" (map dumpFile (reverse deSugared)) ++ "\n"
            Right (toDump, toPrint, typeCheck v (last evalSteps) ++ printErrors v errors)
        )
 where
  printParseError [err] = err
  printParseError errLines = intercalate "\n" (init errLines) ++ "\n"
  dumpFile ("Just", body, _) = "\n\n-- IMPORTED FROM PRELUDE:\n\nJust = " ++ show body
  dumpFile (name, body, _) = name ++ " = " ++ show body
  dumpFileSTC ("Just", body, signature) = "\n\n-- IMPORTED FROM PRELUDE:\n\nJust :: " ++ show signature ++ "\n" ++ "Just = " ++ show body
  dumpFileSTC (name, body, signature) = name ++ " :: " ++ show signature ++ "\n" ++ name ++ " = " ++ show body
  isTrace = isInfixOf " TRACE " file || isInfixOf "(TRACE " file || isInfixOf " TRACE{" file || isInfixOf " TRACE(" file || isInfixOf "(TRACE(" file || isInfixOf "(TRACE{" file

-- Checks to see if the returned lambda was complete, and if not, type checks the lambda to determine the reason
typeCheck :: Int -> Term -> String
typeCheck _ (Exp _) = ""
typeCheck 3 (Abs _ _) = "Warning: The program is incomplete, as the final result is a function which requires an argument but does not have one\n         This was likely caused by too few arguments being given to one or more functions\n\n"
typeCheck _ (Abs _ _) = "Warning: The program is incomplete, as the final result is a function which requires an argument but does not have one\n\n"
typeCheck 3 (App f g) = "Error: The expression '" ++ show f ++ "' does not take any arguments, yet '" ++ show g ++ "' is applied to it\n       This was likely caused by too many arguments being given to one or more functions\n\n"
typeCheck _ (App f g) = "Error: The expression '" ++ show f ++ "' does not take any arguments, yet '" ++ show g ++ "' is applied to it\n\n"
typeCheck _ (Trace _) = ""

-- Pretty prints any errors encountered, at the given verbosity
printErrors :: Int -> [String] -> String
printErrors _ [] = ""
printErrors 3 (e : es) = e ++ "\n\n" ++ printErrors 3 es
printErrors 4 (e : es) = e ++ "\n\n" ++ printErrors 4 es
printErrors v (e : es) = head (lines e) ++ "\n\n" ++ printErrors v es

-- Parses a given file, returning either an error msg, or a list of lambdas showing the evaluation, any errors and the desugared list of functions
parseFile :: String -> String -> Bool -> Either String ([Term], [String], [(String, Term, TermType)])
parseFile file func True = do
  -- With static type checking
  case parse (program func <* eof) "" (pack file) of
    Left bundle -> Left (errorBundlePretty (clean bundle))
    Right (e, es) -> do
      let funcTypes = map (uncurry (inferTermType es) . (\(s, f) -> ([s], f))) es
      let allGood = checkTypes funcTypes
      when (isLeft allGood) (Left (fromLeft "" allGood))
      let ((_, errors), ls) = runWriter $ simplifyTerm es e (Exp (Var "x"))
      Right (ls, errors, addTypeSigs es (fromRight [] allGood))
parseFile file func False = do
  -- Without static type checking
  case parse (program func <* eof) "" (pack file) of
    Left bundle -> Left (errorBundlePretty (clean bundle))
    Right (e, es) -> do
      let ((_, errors), ls) = runWriter $ simplifyTerm es e (Exp (Var "x"))
      Right (ls, errors, addTypeSigs es [])

clean :: ParseErrorBundle Text String -> ParseErrorBundle Text String
clean (ParseErrorBundle es s) = ParseErrorBundle (N.map cleanError es) s

cleanError :: ParseError Text String -> ParseError Text String
cleanError (TrivialError x m es)
  | member (Tokens (N.fromList "*")) es = TrivialError x m (insert (Label (N.fromList "an operator")) $ difference es $ fromList [Tokens (N.fromList "ceiling"), Tokens (N.fromList "floor"), Tokens (N.fromList "*"), Tokens (N.fromList "/"), Tokens (N.fromList "+"), Tokens (N.fromList "-"), Tokens (N.fromList ":"), Tokens (N.fromList "++"), Tokens (N.fromList "=="), Tokens (N.fromList "/="), Tokens (N.fromList "<"), Tokens (N.fromList "<="), Tokens (N.fromList ">"), Tokens (N.fromList ">="), Tokens (N.fromList "&&"), Tokens (N.fromList "||"), Tokens (N.fromList "$")])
  | otherwise = TrivialError x m es
cleanError e = e

-- Repeatedly evaluate a given lambda, step by step, until the lambda no longer changes. Returns the list of Terms and the final lambda evaluation in a Writer.
simplifyTerm :: LUT Term -> Term -> Term -> Writer [Term] (Term, [String])
simplifyTerm _ (Exp (Val (InfiniteList l))) _ = tell [Exp (Val (InfiniteList l))] >> pure (Exp (Val (InfiniteList l)), []) -- this avoids lazy / infinite lists causing crashing when output
simplifyTerm s f g =
  if f == g
    then pure (f, [])
    else do
      tell [f]
      case evalTerm s f of
        Left errors -> pure (f, errors)
        Right e -> simplifyTerm s e f

-- Print the given evaluation steps
-- 1st arg = evaluation steps
-- 2nd arg = 'trace' flag
-- 3rd arg = 'verbosity' flag
output :: [Term] -> Int -> Int -> String -> [String]
output ls 1 _ _ = [show $ last ls]
output ls t v "main" = ("main " ++ head (steps t v ls)) : tail (steps t v ls)
output ls t v _ = steps t v ls

-- Gets the list of evaluation steps and evaluation
-- 1st arg = 'trace' flag
-- 2nd arg = 'verbosity' flag
-- 3rd arg = evaluation steps
steps :: Int -> Int -> [Term] -> [String]
steps t v ls = map fst (mapSteps t v ls True)

-- Gets all evaluation steps
-- 1st arg = 'trace' flag
-- 2nd arg = 'verbosity' flag
-- 3rd arg = evaluation steps
-- 4th arg = bool stating whether the previous step was visible
mapSteps :: Int -> Int -> [Term] -> Bool -> [(String, Bool)]
mapSteps _ _ [] _ = []
mapSteps t v (l:ls) vis
  | vis && not doprint = (fst eval ++ "    [...]", snd eval) : mapSteps t v ls doprint
  | doprint = eval : mapSteps t v ls doprint
  | otherwise = mapSteps t v ls doprint
    where
      (eval, doprint) = outputEvaluation t v l

-- Print the given evaluation steps inside trace blocks
-- 1st arg = evaluation steps
-- 2nd arg = 'trace' flag
-- 3rd arg = 'verbosity' flag
outputTrace :: [Term] -> Int -> Int -> String -> [String]
outputTrace ls 1 _ _ = [show $ last ls]
outputTrace ls t v "main" = ("main " ++ head (steps' t v ls)) : tail (steps' t v ls)
outputTrace ls t v _ = steps t v ls -- TRACE blocks do not stop trace for repl

-- Gets the list of evaluation steps and evaluation, if inside of a TRACE block
-- 1st arg = 'trace' flag
-- 2nd arg = 'verbosity' flag
-- 3rd arg = evaluation steps
steps' :: Int -> Int -> [Term] -> [String]
steps' t v [l] = [fst $ fst $ outputEvaluation t v l]
steps' t v ls = map fst (filter snd (mapSteps t v (init ls) True)) ++ [fst $ fst $ outputEvaluation t v (last ls)]

-- Outputs one step of evaluation
-- 1st arg = 'trace' flag
-- 2nd arg = 'verbosity' flag
-- 3rd arg = evaluation step
outputEvaluation :: Int -> Int -> Term -> ((String, Bool), Bool)
outputEvaluation t v l = (("= " ++ show l ++ expl, snd action), doprint)
  where
    action = nextAction l t v False
    doprint = fst action /= "noprint"
    expl = if v == 1 || not doprint then "" else fst action

-- Determine the explanation that should be given for a lambda evaluation step
-- 1st arg = evaluation step
-- 2nd arg = 'trace' flag
-- 3rd arg = 'verbosity' flag
-- 4th arg = bool to denote if we are currently inside a TRACE block
nextAction :: Term -> Int -> Int -> Bool -> (String, Bool)
nextAction (Exp e) t v b = nextActionExpr e t v b
nextAction (App (Abs x f) g) _ v b = case v of
  2 -> ("    [Beta Reduction]", b)
  3 -> ("    [Replacement of " ++ x ++ " in " ++ show f ++ " with " ++ show g ++ "]", b)
  _ -> ("    [I will replace all free occurrences of " ++ x ++ " in " ++ show f ++ " with " ++ show g ++ "]", b)
nextAction (App f _) t v b = nextAction f t v b
nextAction (Trace f) t v _ = if fst (nextAction f t 3 True) == "" then ("noprint", False) else nextAction f t v True -- don't print if no evaluation happens inside of the TRACE block
nextAction _ _ _ b = ("", b) -- if this happens, program was not complete

-- Determine the explanation that should be given for an expression evaluation step
-- 1st arg = evaluation step
-- 2nd arg = 'trace' flag
-- 3rd arg = 'verbosity' flag
-- 4th arg = bool to denote if we are currently inside a TRACE block
nextActionExpr :: Expr -> Int -> Int -> Bool -> (String, Bool)
nextActionExpr (Var var) _ v b = case v of
  2 -> ("    [Function Replacement]", b)
  3 -> ("    [Replacement of identifier '" ++ var ++ "' with its function body]", b)
  _ -> ("    [I will replace the function identifier '" ++ var ++ "' with its function body]", b)
-- nextActionExpr (Function l) t v b = nextAction l t v b
nextActionExpr (Val x) t v b = nextActionVal x t v b
nextActionExpr (Error _) _ _ _ = ("", False)
nextActionExpr (UnOp Negation (Exp (Var _))) _ _ _ = ("noprint", False) -- negation function does not need an eval step
nextActionExpr (UnOp Negation (Exp (Val _))) _ _ _ = ("noprint", False) -- negation function does not need an eval step
nextActionExpr (UnOp Negation e) t v b = nextAction e t v b
nextActionExpr (UnOp Floor (Exp (Val x))) 4 v b = case v of
  2 -> ("    [Floor]", b)
  3 -> ("    [Floor of " ++ show x ++ "]", b)
  _ -> ("    [I will round " ++ show x ++ " down to the nearest integer]", b)
nextActionExpr (UnOp Floor (Exp (Val _))) _ _ _ = ("noprint", False)
nextActionExpr (UnOp Floor x) t v b = nextAction x t v b
nextActionExpr (UnOp Ceiling (Exp (Val x))) 4 v b = case v of
  2 -> ("    [Ceiling]", b)
  3 -> ("    [Ceiling of " ++ show x ++ "]", b)
  _ -> ("    [I will round " ++ show x ++ " up to the nearest integer]", b)
nextActionExpr (UnOp Ceiling (Exp (Val _))) _ _ _ = ("noprint", False)
nextActionExpr (UnOp Ceiling x) t v b = nextAction x t v b
nextActionExpr (BinOp Sum (Exp (Val x)) (Exp (Val y))) 4 v b = case v of
  2 -> ("    [Addition]", b)
  3 -> ("    [Addition of " ++ show x ++ " and " ++ show y ++ "]", b)
  _ -> ("    [I will add together " ++ show x ++ " and " ++ show y ++ "]", b)
nextActionExpr (BinOp Sum (Exp (Val _)) (Exp (Val _))) _ _ _ = ("noprint", False)
nextActionExpr (BinOp Sum (Exp (Val _)) y) t v b = nextAction y t v b
nextActionExpr (BinOp Sum x _) t v b = nextAction x t v b
nextActionExpr (BinOp Subtr (Exp (Val x)) (Exp (Val y))) 4 v b = case v of
  2 -> ("    [Subtraction]", b)
  3 -> ("    [Subtraction of " ++ show y ++ " from " ++ show x ++ "]", b)
  _ -> ("    [I will subtract " ++ show y ++ " from " ++ show x ++ "]", b)
nextActionExpr (BinOp Subtr (Exp (Val _)) (Exp (Val _))) _ _ _ = ("noprint", False)
nextActionExpr (BinOp Subtr (Exp (Val _)) y) t v b = nextAction y t v b
nextActionExpr (BinOp Subtr x _) t v b = nextAction x t v b
nextActionExpr (BinOp Product (Exp (Val x)) (Exp (Val y))) 4 v b = case v of
  2 -> ("    [Product]", b)
  3 -> ("    [Product of " ++ show x ++ " and " ++ show y ++ "]", b)
  _ -> ("    [I will multiply together " ++ show x ++ " and " ++ show y ++ "]", b)
nextActionExpr (BinOp Product (Exp (Val _)) (Exp (Val _))) _ _ _ = ("noprint", False)
nextActionExpr (BinOp Product (Exp (Val _)) y) t v b = nextAction y t v b
nextActionExpr (BinOp Product x _) t v b = nextAction x t v b
nextActionExpr (BinOp Division (Exp (Val x)) (Exp (Val y))) 4 v b = case v of
  2 -> ("    [Division]", b)
  3 -> ("    [Division of " ++ show x ++ " by " ++ show y ++ "]", b)
  _ -> ("    [I will divide " ++ show x ++ " by " ++ show y ++ "]", b)
nextActionExpr (BinOp Division (Exp (Val _)) (Exp (Val _))) _ _ _ = ("noprint", False)
nextActionExpr (BinOp Division (Exp (Val _)) y) t v b = nextAction y t v b
nextActionExpr (BinOp Division x _) t v b = nextAction x t v b
nextActionExpr (BinOp Cons x (Exp (Val y))) 4 v b = case v of
  2 -> ("    [Cons]", b)
  3 -> ("    [Cons of " ++ show x ++ " and " ++ show y ++ "]", b)
  _ -> ("    [I will prepend " ++ show x ++ " to the list " ++ show y ++ "]", b)
nextActionExpr (BinOp Cons _ (Exp (Val _))) _ _ _ = ("noprint", False)
nextActionExpr (BinOp Cons _ y) t v b = nextAction y t v b
nextActionExpr (BinOp Append (Exp (Val x)) (Exp (Val y))) 4 v b = case v of
  2 -> ("    [Append]", b)
  3 -> ("    [Append of " ++ show y ++ " to " ++ show x ++ "]", b)
  _ -> ("    [I will Append the list " ++ show y ++ " to the list " ++ show x ++ "]", b)
nextActionExpr (BinOp Append (Exp (Val _)) (Exp (Val _))) _ _ _ = ("noprint", False)
nextActionExpr (BinOp Append (Exp (Val _)) y) t v b = nextAction y t v b
nextActionExpr (BinOp Append x _) t v b = nextAction x t v b
nextActionExpr (Case (Exp (Val x)) ys) t v b = case nextActionVal x t v b of
  ("", _) -> nextActionCase x ys t v b
