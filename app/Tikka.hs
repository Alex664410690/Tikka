-- Parse an entire program, returning the main expression, and the list of function references
-- 1st arg = function to evaluate (usually main)
program :: String -> Parser (Term, LUT Term)
program func = do
  _ <- lexeme ""
  as <- many $ lexeme pItemList -- lexeme removes multi-line comments
  let cs = [b ++ " " ++ unwords bs | (b, bs) <- as, b /= ""]
  case parseDecl cs of
    Left s -> customFailure s
    Right fs -> do
      let gs = foldr combine [] fs
      case toTerm gs of
        Left s -> customFailure s
        Right hs -> case getFunc hs func of
          Nothing ->
            if func == "main"
              then customFailure "Error: No main function defined\n             Every program should contain a function called 'main' which is where the program is entered, and evaluation starts"
              else customFailure $ "Error: No function " ++ func ++ " defined"
          Just e -> pure (e, hs)

-- Split up functions by their indentation (new functions begin on non-idented lines)
pItemList :: Parser (String, [String])
pItemList =
  (space1 >> pure ("", [])) <|> do
    header <- pItem False
    items <- many $ hspace1 >> pItem (not (null (indices "case" (pack header))))
    pure (header, items)

-- Take one indented line if possible, to be appended on the previous line
pItem :: Bool -> Parser String
pItem isCase = do
  x <- some $ noneOf ['\n', '\r']
  try eof <|> void eol
  if isCase && not (null (indices "->" (pack x))) && null (indices ";" (pack x)) then pure (x ++ ";") else pure x

-- parse the text into function declarations
parseDecl :: [String] -> Either String (LUT ([Term], Term))
parseDecl [] = Right []
parseDecl (c : cs) = case parse (moduleImport <|> try typeSig <|> try dataType <|> funcDecl) "" (pack c) of
  Left bundle -> Left $ unpack $ replace "input" "declaration" $ pack $ errorBundlePretty $ clean bundle
  Right [x] -> case parseDecl cs of
    Left s -> Left s
    Right xs -> Right (x : xs)
  Right y -> case parseDecl cs of
    Left s -> Left s
    Right ys -> Right (y ++ ys)

-- Throws an error if an imported module tries to import a module
moduleImport :: Parser (LUT ([Term], Term))
moduleImport = do
  lexeme "import"
  customFailure "Error: Only the module being run can import other modules in Tikka\n       This means that imported modules cannot use the 'import' keyword themselves"

-- Parse a custom datatype declaration
dataType :: Parser (LUT ([Term], Term))
dataType = do
  lexeme "data"
  n <- identifier'
  many identifier -- parses polymorphic datatypes in the form 'Maybe a = Just a | Nothing'
  lexeme "="
  c' <- typeCon
  cs <- many typeCons
  pure $ map (makeDT n) (c' : cs)
 where
  makeDT n (c, ts) = (c, (vars ts, Exp . Val $ CustomDT c (vars ts) (V n ts)))
  vars x = generateVars (length x)

-- Parses one decalaration of a type constructor
typeCon :: Parser (String, [TermType])
typeCon = do
  c <- identifier'
  xs <- many typeIdentifier
  let ts = typeReadAll 0 xs
  pure (c, ts)

-- Parses the rest of the type constructors
typeCons :: Parser (String, [TermType])
typeCons = do
  lexeme "|"
  typeCon

-- Reads in a list of types and converts it to a list of TermTypes
typeReadAll :: Int -> [String] -> [TermType]
typeReadAll _ [] = []
typeReadAll i (x : xs) = case typeRead i x of
  (N j) -> N j : typeReadAll (j + 1) xs
  t -> t : typeReadAll i xs

-- Reads in a type and converts it to an TermType
typeRead :: Int -> String -> TermType
typeRead i x
  | x == "" = error "Empty type"
  | head x `elem` ['a' .. 'z'] = N i
  | head x == '[' && last x == ']' = V "list" [typeRead i (tail $ init x)]
  | head x == '(' && last x == ')' = V "list" (map (typeRead i . trim) (splitOn "," (tail $ init x)))
  | otherwise = V x []
 where
  trim = dropWhileEnd isSpace . dropWhile isSpace

-- Disregards type signatures
typeSig :: Parser (LUT ([Term], Term))
typeSig = do
  i <- varIdentifier
  lexeme "::"
  r <- takeRest
  pure [("0typeSig", ([], Exp . Var $ i ++ " :: " ++ unpack r))]

-- Parse a function declaration/definition from Text into a name, list of arguments and a body
funcDecl :: Parser (LUT ([Term], Term))
funcDecl = do
  i <- varIdentifier
  vars <-
    many $
      choice
        [ try listPattern
        , try (Exp . Val <$> consPattern)
        , try (parens expr)
        , Exp <$> value
        , try (Exp . Var <$> identifier')
        , Exp <$> variable
        ]
  lexeme "="
  body <- expr
  lexeme $ many ";"
  eof <|> void undefinedTerm <|> do
    es <- some expr
    customFailure ("Error: The expression '" ++ show body ++ "' does not take any arguments, yet '" ++ unwords (map show es) ++ "' is applied to it\n             This means that more was found after the end of a definition (maybe there are missing brackets?)")
  pure [(i, (vars, body))]

-- Used by repl to check if a function is well-defined
isFunction :: Text -> Maybe String
isFunction t =
  if head (splitOn " " (unpack t)) == "data"
    then case parse dataType "" t of
      Left bundle -> Just (errorBundlePretty (clean bundle))
      Right _ -> Nothing
    else case parse funcDecl "" t of
      Left bundle -> Just (errorBundlePretty (clean bundle))
      Right _ -> Nothing

-- Add a function definition to a list of definitions, where those with the same name are combined
-- 1st arg = new function definition
-- 2nd arg = list of definitions
combine :: (String, ([Term], Term)) -> [(String, [([Term], Term)])] -> [(String, [([Term], Term)])]
combine ("0typeSig", _) fs = fs
combine (name, f) [] = [(name, [f])]
combine (name, f) ((name', fs) : gs) =
  if name == name'
    then (name, f : fs) : gs
    else (name', fs) : combine (name, f) gs

-- Desugars function arguments to abstractions, and creates a case statement for pattern matching where needed
toTerm :: [(String, [([Term], Term)])] -> Either String (LUT Term)
toTerm [] = Right []
toTerm ((name, cases) : fs) = case createTerm name cases of
  Left s -> Left s
  Right e -> case toTerm fs of
    Left a -> Left a
    Right b -> Right $ (name, e) : b
 where
  createTerm n cs =
    if length cs == 1
      then Right $ createAbs (head cs)
      else case checkCases cs of
        Just x -> Right x
        Nothing -> Left $ "Error: The function '" ++ n ++ "' is declared with different numbers of arguments\n       Functions can be declared multiple times (for example for pattern matching), but each declaration must have the same number of arguments / inputs. Perhaps you accidentally reused a function name?"

-- Creates an abstraction from a list of inputs and an expression
createAbs :: ([Term], Term) -> Term
createAbs ((Exp (Var s)) : es, body) = Abs s $ createAbs (es, body)
createAbs ([], body) = body
createAbs es = createPatternMatch [es]

-- Checks that each case has the same number of arguments
checkCases :: [([Term], Term)] -> Maybe Term
checkCases [] = Nothing -- Should never happen
checkCases ((args, e) : es) = if sameNumberOfArgs es (length args) then Just $ createPatternMatch ((args, e) : es) else Nothing
 where
  sameNumberOfArgs [] _ = True
  sameNumberOfArgs ((a, _) : as) n = (length a == n) && sameNumberOfArgs as n

-- Creates a case statement for pattern matching from a list of inputs
createPatternMatch :: [([Term], Term)] -> Term
createPatternMatch [] = Exp $ Var "x" -- Should never happen
createPatternMatch ((xs, x) : es) = createAbs (vars, createCases vars ((xs, x) : es))
 where
  vars = generateVars (length xs)

-- Creates the case statement with a list of variables and potential values
createCases :: [Term] -> [([Term], Term)] -> Term
createCases [var] es = Exp $ Case var [(as, a) | ([as], a) <- es]
createCases vars es = Exp $ Case (Exp $ Val $ Tuple vars) [(Exp $ Val $ Tuple as, a) | (as, a) <- es]

-- Generates a list of unique variable names, of the form 'xvar' where x is an integer
generateVars :: Int -> [Term]
generateVars 0 = []
generateVars n = Exp (Var (show n ++ "var")) : generateVars (n - 1)

-- Gets the function to be evaluated from the list of references
getFunc :: LUT Term -> String -> Maybe Term
getFunc [] _ = Nothing
getFunc ((n, x) : t) s = if n == s then Just x else getFunc t s
