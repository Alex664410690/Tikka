-- Determine the explanation that should be given for an expression evaluation step
-- 1st arg = evaluation step
-- 2nd arg = 'trace' flag
-- 3rd arg = 'verbosity' flag
-- 4th arg = bool to denote if we are currently inside a TRACE block
nextActionVal :: Value -> Int -> Int -> Bool -> (String, Bool)
nextActionVal (Tuple (e : es)) t v b = case nextAction e t v b of
  ("", _) -> nextActionVal (Tuple es) t v b
  x -> x
nextActionVal (List (e : es)) t v b = case nextAction e t v b of
  ("", _) -> nextActionVal (List es) t v b
  x -> x
nextActionVal (ListPattern y z) t v b = case nextAction y t v b of
  ("", _) -> nextAction z t v b
  x -> x
nextActionVal (CustomDT n (e : es) ty) t v b = case nextAction e t v b of
  ("", _) -> nextActionVal (CustomDT n es ty) t v b
  x -> x
nextActionVal _ _ _ b = ("", b)

-- Determine the explanation that should be given for a case expression evaluation step
-- 1st arg = value to replace with
-- 2nd arg = cases
-- 3rd arg = 'trace' flag
-- 4th arg = 'verbosity' flag
-- 5th arg = bool to denote if we are currently inside a TRACE block
nextActionCase :: Value -> [(Term, Term)] -> Int -> Int -> Bool -> (String, Bool)
nextActionCase _ _ 2 _ _ = ("noprint", False)
nextActionCase _ [] _ v b = case v of
  2 -> ("    [Pattern Simplification & Possible Case Selection]", b)
  3 -> ("    [Pattern Simplification & Possible Case Selection]", b)
  _ -> ("    [I will fully simplify the pattern for each case and select it if it matches]", b)
nextActionCase _ ((Exp (Var "_"), z) : _) _ v b = case v of
  2 -> ("    [Case Selection]", b)
  3 -> ("    [Case Selection of " ++ show z ++ "]", b)
  _ -> ("    [I will select the expression " ++ show z ++ " because the pattern is a wildcard ('_')]", b)
nextActionCase x ((Exp (Var y), z) : _) t v b =
  if head y `elem` ['A' .. 'Z']
    then nextActionExpr (Var y) t v b
    else case v of
      2 -> ("    [Case Selection with variable replacement]", b)
      3 -> ("    [Case Selection of " ++ show z ++ " with replacement of " ++ y ++ " with " ++ show x ++ "]", b)
      _ -> ("    [I will select the expression " ++ show z ++ " and replace all instances of " ++ y ++ " with " ++ show x ++ "]", b)
nextActionCase x ((Exp (Val y), z) : ys) t v b =
  if null toReplace
    then nextActionCase x ys t v b
    else case (toReplace, v) of
      (Just [], 2) -> ("    [Case Selection]", b)
      (Just [], 3) -> ("    [Case Selection of " ++ show z ++ "]", b)
      (Just [], _) -> ("    [I will select the expression " ++ show z ++ " because the pattern is " ++ show y ++ "]", b)
      (_, 2) -> ("    [Case Selection with variable replacement]", b)
      (Just xs, 3) -> ("    [Case Selection " ++ show z ++ " with replacement of " ++ getVars xs ++ "]", b)
      (Just xs, _) -> ("    [I will select the expression " ++ show z ++ " and replace all instances of " ++ getVars xs ++ "]", b)
      (Nothing, _) -> ("    [I will select the expression for the matching case]", b)
 where
  toReplace = fst . runWriter $ matched [] x y
  getVars [(s, r)] = "and " ++ s ++ " with " ++ show r
  getVars ((s, r) : rs) = s ++ " with " ++ show r ++ ", " ++ getVars rs
  getVars _ = "" -- Should never happen
nextActionCase _ ((y, _) : _) t v b = nextAction y t v b

